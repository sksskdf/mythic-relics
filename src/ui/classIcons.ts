const cache = new Map<string, string>()

/** 클래스 아이콘 그림 주소. 없는 이름이면 빈 문자열 */
export function classIcon(name: string): string {
  let url = cache.get(name)
  if (url === undefined) {
    const def = CLASS_ICONS[name]
    url = def ? pixelIcon(def.rows, def.colors) : ''
    cache.set(name, url)
  }
  return url
}
